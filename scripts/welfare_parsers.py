# 급여 종류별 법정 기준(기준 중위소득 %)
_BENEFIT_PCT = [
    ("생계급여", 32), ("의료급여", 40), ("주거급여", 48), ("교육급여", 50),
    ("차상위", 50), ("기초생활", 50), ("수급자", 50),
]


def parse_income_pct(*texts):
    """
    소득 조건을 기준 중위소득 % 로 반환. (상한, 하한) 튜플. 못 찾으면 (None, None).

    "중위소득 150% 이하" 처럼 그 값 '이하'만 받는 게 보통이지만,
    "중위소득 150% 초과" 처럼 정반대로 그 값을 '넘는' 사람만 받는 사업도
    실제로 34건 있었다(주로 산모·신생아 건강관리 지원의 '추가형'·'확대'
    버전 — 저소득층 지원과 별개로, 중위소득 초과라 다른 지원을 못 받는
    가구를 메워주는 사업). 방향을 안 가리고 숫자만 뽑으면 이런 사업은
    상한선을 정반대로 적용해, 대상자(고소득)를 걸러내고 비대상자(저소득)를
    통과시키는 거꾸로 된 필터가 된다.
    """
    blob = " ".join(t for t in texts if t)
    if not blob:
        return None, None

    # 1) '중위소득 150% 이하/미만/초과/이상' — 숫자 뒤 방향어까지 함께 본다
    m = re.search(r"중위\s*소득\s*(?:의\s*)?(\d{2,3})\s*%\s*(이하|미만|초과|이상)?", blob)
    if m:
        pct = int(m.group(1))
        direction = m.group(2)
        if 10 <= pct <= 300:
            if direction in ("초과", "이상"):
                return None, pct       # 하한: 이 값을 넘어야 대상
            return pct, None           # 상한(기본): 이 값 이하만 대상

    # 2) 급여 종류로 유추 (전부 '이하' 방향의 저소득 지원 제도)
    #
    # 급여 이름이 자격 조건이 아니라 행정 절차 설명으로 스쳐 지나가는
    # 경우가 있어 문맥을 함께 본다. 아동수당 지원대상에는 "사회복지
    # 전산관리번호(의료급여 전산관리번호) 부여 대상자 포함"이라는 문구가
    # 있는데, 이걸 자격으로 읽으면 만 8세 미만 모든 아동이 받는 수당에
    # 중위소득 40% 상한이 붙어 웬만한 가구에서 통째로 사라진다.
    for kw, pct in _BENEFIT_PCT:
        if _kw_present(blob, kw):
            return pct, None
    return None, None


# 서비스명에만 소득 조건이 드러나는 경우가 많다.
#   예) "차상위이하 아동 방과후 보육료" — 지원대상·선정기준 칸이 통째로 비어
#       있어(지자체가 API에 안 채움) 소득 조건이 하나도 안 잡혔다. 그래서
#       중위소득 120% 가구에도 차상위 전용 사업이 그대로 노출됐다.
#
# 다만 이름에 든 말은 스치듯 쓰이기도 해서(예: "기초연금 수급자 확인서"의
# '수급자'는 발급 대상 설명일 뿐 소득 상한이 아니다) 뜻이 분명한 말만 쓴다.
# '저소득'·'수급자'처럼 폭이 넓거나 모호한 말은 일부러 뺐다 — 잘못 걸면
# 받을 수 있는 사람에게서 사업이 사라지는데, 그 손해가 더 크다.
_NAME_BENEFIT_PCT = [
    ("차상위", 50), ("기초생활수급", 50), ("기초생활보장", 50),
    ("생계급여", 32), ("의료급여", 40), ("주거급여", 48), ("교육급여", 50),
]


def income_pct_from_name(name: str):
    """서비스명만으로 소득 상한(기준 중위소득 %)을 유추한다. 없으면 None."""
    if not name:
        return None
    for kw, pct in _NAME_BENEFIT_PCT:
        if kw in name:
            return pct
    return None



# 대상이 여러 갈래로 나열된 사업. 이런 문서에서 '자녀'·'임산부'는
# 그중 한 갈래일 뿐 필수 조건이 아니다.
#   예) 주차요금 감면 - "장애인, 국가유공자, 2자녀 이상, 임산부 탑승 차량"
# 이걸 필수로 보면 자녀 없는 사람에게 주차 감면이 통째로 사라진다.
# 감면·할인 대상을 여러 갈래로 나열한 문서인지 판단한다.
# 단순히 '무료'·'감면' 이 들어 있는지만 보면
# "무료 임차 소득"(기초연금 소득 산정 항목) 같은 표현에도 걸려
# 기초연금의 나이 조건(만 65세 이상)을 통째로 잃는다.
# 그래서 '○ 50% 할인 :' 처럼 항목 앞에 붙은 형태만 인정한다.
_MULTI_TARGET_RE = re.compile(
    r"[○❍◦·▪-]\s*[^\n○❍]{0,20}(감면|할인|면제|무료)[^\n○❍]{0,10}[:：]"
    r"|(감면|할인)\s*(대상|율|액)\s*[:：]"
    r"|\d+\s*%\s*(감면|할인|면제)")


def _is_multi_target(blob: str) -> bool:
    """여러 대상을 나열한 감면·할인 문서인지."""
    return bool(_MULTI_TARGET_RE.search(blob))


def needs_child(*texts):
    """자녀가 있어야만 받을 수 있는 사업인지.

    여러 대상을 나열한 문서에서는 '자녀'가 스치듯 나와도 필수로 보지 않는다.
    """
    blob = " ".join(t for t in texts if t)
    if any(k in blob for k in _NOT_CHILD_KW):
        return False
    if not any(k in blob for k in _CHILD_KW):
        return False
    # 임신·출산 사업은 아직 아이가 없는 단계다. 자녀 유무로 자르면 안 된다.
    if is_pregnancy(*texts):
        return False
    # 서비스명 자체가 아이 대상이면 확실하다 (부모급여, 아동수당 등)
    name = texts[0] if texts else ""
    if any(k in name for k in _CHILD_KW):
        return True
    return not _is_multi_target(blob)


def is_pregnancy(*texts):
    """임신 중이어야만 받을 수 있는 사업인지.

    needs_child 와 같은 이유로, 여러 대상을 나열한 문서에서는
    '임산부'가 한 줄 나와도 필수 조건으로 보지 않는다.
    """
    blob = " ".join(t for t in texts if t)
    if not any(k in blob for k in _PREG_KW):
        return False
    name = texts[0] if texts else ""
    if any(k in name for k in _PREG_KW):
        return True
    return not _is_multi_target(blob)


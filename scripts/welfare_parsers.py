def _kw_present(blob: str, kw: str, tag: str = "") -> bool:
    """키워드가 '진짜 그 뜻으로' 등장하는지. 예외 문맥은 세지 않는다."""
    rejects = tuple(_KW_REJECT.get(kw, ()))
    if tag:
        rejects += tuple(_TAG_KW_REJECT.get((tag, kw), ()))
    if not rejects:
        return kw in blob
    start = 0
    while True:
        i = blob.find(kw, start)
        if i == -1:
            return False
        window = blob[max(0, i - 8): i + len(kw) + 15]
        if not any(r in window for r in rejects):
            return True          # 예외가 아닌 등장이 하나라도 있으면 인정
        start = i + len(kw)


def _any_kw(blob: str, kws, tag: str = "") -> bool:
    return any(_kw_present(blob, k, tag) for k in kws)



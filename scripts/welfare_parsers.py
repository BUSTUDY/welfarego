"""
정부 API의 자연어 필드에서 매칭용 구조화 값을 뽑아내는 파서.

왜 필요한가
-----------
API는 '지원대상'을 "만 19세~34세 청년 중 기준 중위소득 150% 이하"처럼
사람이 읽는 문장으로만 준다. 나이·소득 필터는 숫자가 있어야 작동하므로
여기서 텍스트 -> 숫자로 바꾼다. 이 모듈이 없으면 실데이터에서
나이·소득·상황 필터가 전부 무효가 된다.

원칙: 확신이 없으면 None을 반환한다. 잘못된 숫자로 거르는 것보다
      안 거르고 보여주는 쪽이 안전하다(복지 정보는 누락이 더 치명적).
"""

import re

# ---------------------------------------------------------------- 나이
# 순서가 중요하다. '만 19세 이상 34세 이하'처럼 상·하한이 모두 적힌 표현을
# 먼저 잡지 않으면 '19세 이상'에서 매칭이 끝나 상한(34)을 통째로 잃는다.
# 한국 복지 문서에서 가장 흔한 청년 연령 표기라 영향이 크다.
_AGE_PATTERNS = [
    # 만 19세 이상 34세 이하 / 19세 이상 35세 미만 / 19세 이상 ~ 34세 이하
    (r"만?\s*(\d{1,3})\s*세\s*이상[\s~\-–,및부터에서]*(?:만\s*)?(\d{1,3})\s*세\s*(미만|이하)",
     "range_excl"),
    # 만 19세 ~ 34세 / 만 19~34세 / 19세부터 34세까지
    (r"만?\s*(\d{1,3})\s*세?\s*[~\-–부터]+\s*(?:만\s*)?(\d{1,3})\s*세", "range"),
    # 만 65세 이상
    (r"만?\s*(\d{1,3})\s*세\s*이상", "min"),
    # 만 8세 미만 / 18세 이하
    (r"만?\s*(\d{1,3})\s*세\s*(미만|이하)", "max"),
    # 0~1세, 0~5세 (영유아)
    (r"(\d{1,2})\s*[~\-–]\s*(\d{1,2})\s*세", "range"),
]


# 나이 표현 바로 앞뒤에 이런 말이 있으면 그 나이는 '신청자'가 아니라 '아이'의 나이다.
# 예: "0~5세 아동에게 보육료 지원" -> 신청자는 부모(30~40대)인데
#     아이 나이를 신청자 나이로 읽으면 정작 부모가 결과에서 사라진다.
# 아이를 명확히 가리키는 말만 넣는다.
# '청소년·학생'은 본인이 신청자인 경우가 많아(청소년한부모, 대학생 장학금) 넣지 않는다.
_CHILD_AGE_KW = ("아동", "어린이", "영유아", "영아", "유아", "자녀", "아이",
                 "신생아", "출생아", "미취학", "보육료", "양육수당", "어린이집")


def is_child_age(text: str) -> bool:
    """지원대상에 적힌 나이가 아이 나이인지 판단.

    감면 대상을 여러 갈래로 나열한 문서(주차요금 감면 등)에서는
    '2자녀이상(막내 만 18세 이하)' 같은 표현이 한 줄 나올 뿐이다.
    이걸 아이 나이로 보면 그 사업 전체가 자녀 필수로 바뀐다.
    """
    if not text:
        return False
    if _is_multi_target(text):
        return False
    t = str(text)
    m = re.search(r"만?\s*\d{1,3}\s*[세개]", t)
    if not m:
        return False
    # 나이 표현 주변 25자 안에 아이를 가리키는 말이 있는지
    near = t[max(0, m.start() - 25): m.end() + 25]
    if any(k in near for k in _CHILD_AGE_KW):
        # '청년', '어르신' 처럼 신청자 본인을 가리키는 말이 더 가까우면 제외
        if any(k in near for k in ("청년", "어르신", "노인", "가구주", "세대주")):
            return False
        return True
    return False


_ELDERLY_KW = ("노인", "어르신", "고령자", "고령의", "독거노인", "치매")


# 지원대상에 나이가 없어도 서비스명이 노인 대상임을 말해주는 경우가 있다.
#   예) "노인장기요양 재가급여 지원" -> 대상은 "기초생활수급자" 로만 적힘
# 이름을 함께 보지 않으면 40대에게도 노인 사업이 뜬다.
_ELDERLY_NAME = ("노인", "어르신", "장기요양", "경로", "치매", "고령")


def parse_age(text: str, name: str = ""):
    """(age_min, age_max) 반환. 못 찾으면 (None, None).

    나이가 안 적혀 있어도 '노인·어르신' 대상이면 65세 이상으로 본다.
    이 보정이 없으면 나이 조건이 없어 30대에게도 노인 사업이 뜬다.

    감면 대상을 여러 갈래로 나열한 문서에서는 나이를 읽지 않는다.
    '2자녀이상(막내 만 18세 이하)' 처럼 한 갈래에만 붙은 조건을
    사업 전체의 나이 제한으로 오해하면, 실제로는 장애인·국가유공자도
    받을 수 있는 주차 감면이 18세 이하에게만 보이게 된다.
    """
    # 감면·할인 대상을 나열한 문서에서는 나이를 읽지 않는다.
    # 다만 노인·청년처럼 대상 자체가 연령층인 사업은 예외다.
    #   예) "○ 경로식당 무료급식 : 60세 이상 어르신" 은
    #       할인 목록이 아니라 그냥 대상 설명이다.
    if text and _is_multi_target(text):
        age_target = any(k in (name or "") for k in _ELDERLY_NAME) or \
                     any(k in (text or "") for k in ("어르신", "노인", "청년"))
        if not age_target:
            return None, None
    if not text:
        return None, None
    t = text.replace(" ", " ")
    # 제외 목록에 적힌 나이는 자격이 아니다.
    #   국민내일배움카드 지원대상: "○ 국민 누구나 / ○ 지원 제외 대상 …
    #                              ⑥ 만 75세 이상자 등"
    # 여기서 '만 75세 이상'을 자격으로 읽어 age_min=75 가 붙었고, 그 바람에
    # 누구나 받는 카드가 청년·중장년 구직자에게서 통째로 사라졌다.
    # 같은 문단 앞쪽에 '제외' 같은 말이 있으면 그 매칭은 건너뛴다.
    for pat, kind in _AGE_PATTERNS:
        for m in re.finditer(pat, t):
            if _age_excluded(t, m.start()):
                continue
            if kind == "range_excl":
                lo, hi = int(m.group(1)), int(m.group(2))
                if m.group(3) == "미만":
                    hi -= 1                   # '35세 미만' = 34세까지
                if lo <= hi <= 120:
                    return lo, hi
            elif kind == "range":
                lo, hi = int(m.group(1)), int(m.group(2))
                if lo <= hi <= 120:
                    return lo, hi
            elif kind == "min":
                lo = int(m.group(1))
                if lo <= 120:
                    return lo, 120
            elif kind == "max":
                hi = int(m.group(1))
                if m.group(2) == "미만":      # 매칭된 부분으로 판단해야 정확하다
                    hi -= 1
                if 0 <= hi <= 120:
                    return 0, hi

    # 명시된 나이가 없을 때만 대상 표현으로 보정한다.
    # 나이가 안 적힌 청년 사업이 342건인데, 그대로 두면 60대에게도 뜬다.
    # 청년기본법 기준(19~34세)보다 넓게 잡아 실제로 받을 수 있는 사람을
    # 놓치지 않으면서, 명백히 벗어난 연령은 걸러낸다.
    if any(k in t for k in _ELDERLY_KW):
        return 65, 120
    if name and any(k in name for k in _ELDERLY_NAME):
        return 65, 120
    if any(k in t for k in ("청년", "청년층")):
        return 19, 39
    if any(k in t for k in ("어린이", "아동", "영유아", "유아")):
        return None, None      # 아이 나이는 is_child_age 가 따로 처리
    return None, None



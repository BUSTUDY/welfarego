# 아래 태그가 붙은 사업은 그 상황인 사람만 받을 수 있다.
# 태그를 고르지 않았다고 모두에게 보여주면, 장애인 전용 사업이
# 비장애인에게, 보훈 사업이 일반인에게 뜬다.
#   실데이터에서 장애인 56건 + 보훈 39건이 그렇게 노출됐다.
# 자격이 있어야 받는 사업. 해당 상황을 고르지 않으면 결과에 나오지 않는다.
# '의료비'는 누구나 해당될 수 있으므로 여기에 넣지 않는다.
EXCLUSIVE_TAGS = ("장애인", "국가보훈", "한부모", "다자녀", "다문화")


def exclusive_tags(tags):
    """자격요건에 해당하는 태그만 골라낸다."""
    return [t for t in (tags or []) if t in EXCLUSIVE_TAGS]



# '이 사례는 제외: 노숙인 자활시설 거주자...'처럼 특정 집단을 제외 대상으로만
# 나열하는 문구가 있다. 이 안에 쓰인 단어를 그대로 특수 대상 판정에 쓰면,
# 국민 전체가 받는 생계급여 같은 사업이 '노숙인 전용'으로 둔갑해 일반
# 사용자에게서 사라진다(실사례: 생계급여 지원대상에 위 문구가 있어 통째로
# '노숙인' 특수 대상으로 잘못 분류됨). 매칭 위치 바로 앞에 이런 말이 있으면
# 그 매칭은 세지 않는다.
_NEGATION_KW = ("제외", "포함", "해당하지 않", "받지 않는",
                "받지 못하는", "받을 수 없는", "빼고")
# '포함'은 "복수국적자 포함", "난민 인정 아동 포함"처럼 여러 예외적
# 자격을 나열할 때도 흔히 쓰인다. 주요 대상(대한민국 국적 아동 등)은
# 이미 그 앞에서 조건 없이 다뤄지고, '포함'은 그 주변부 사례를
# 덧붙이는 말이라 이 단어가 가까이 있으면 특수 대상으로 단정하지 않는다.


_PARA_BOUNDARY_RE = re.compile(r"[○❍◦]")


def _negated_near(blob, idx):
    """idx 앞의 '같은 문단'에 제외·부정 표현이 있는지 본다.

    생계급여처럼 '○ 단, ... 제외\\n - 노숙인 ...\\n - 북한이탈주민 ...'
    처럼 제외 문구 하나가 글머리 기호(- ) 여러 줄에 걸쳐 적용되는 경우가
    많다. 고정된 글자수(예: 30자)만 보면 뒤쪽 줄의 단어는 놓친다.
    그래서 앞으로 가장 가까운 문단 시작(○ 등)까지를 한 단위로 보고
    그 구간 전체에서 찾는다 — 그보다 앞선 문단(다른 조건 설명)까지
    새지 않도록 경계를 둔다.
    """
    search_start = max(0, idx - 400)   # 과도한 역주행 방지용 상한
    segment = blob[search_start:idx]
    marks = list(_PARA_BOUNDARY_RE.finditer(segment))
    if marks:
        segment = segment[marks[-1].start():]
    return any(neg in segment for neg in _NEGATION_KW)


# 나이 표현을 건너뛸 근거. _NEGATION_KW 를 그대로 쓰면 안 된다 — 거기에는
# '포함'이 들어 있는데, 지원대상 문구에 '…포함'은 아주 흔해서 인턴십·청년
# 바우처처럼 정상적인 나이 조건까지 통째로 지워버렸다.
_AGE_EXCLUDE_KW = ("제외", "해당하지 않", "지원하지 않", "대상 아님",
                   "지원 불가", "신청 불가")


def _age_excluded(blob, idx):
    """그 나이 표현이 '지원 제외 대상' 목록 안에 있는지.

    문단 어디든 '제외'가 있으면 배제로 보면 안 된다. 괄호 안 여담으로
    쓰이는 경우가 훨씬 많다.
      · "(기 수혜자 제외) … 연령: 24~29세"        <- 24~29세는 진짜 자격
      · "(국가예방접종 대상자 제외, 기초생활수급자의 경우 만 50세 이상)"
    그래서 문단 '머리말'이 제외 목록임을 선언한 경우만 인정한다.
      · "○ 지원 제외 대상  ① 공무원 …  ⑥ 만 75세 이상자"  <- 배제 조건
    """
    seg = blob[max(0, idx - 400):idx]
    marks = list(_PARA_BOUNDARY_RE.finditer(seg))
    if not marks:
        return False
    head = seg[marks[-1].start():][:24]      # 문단 머리말만 본다
    return any(k in head for k in _AGE_EXCLUDE_KW)


def _has_real_match(blob, kws):
    """kws 중 하나라도 제외 문구 밖에서 등장하면 True.

    parse_tags 의 EXCLUSIVE_TAGS 재확인과 is_org_only 판정에 쓴다."""
    for kw in kws:
        start = 0
        while True:
            idx = blob.find(kw, start)
            if idx == -1:
                break
            if not _negated_near(blob, idx):
                return True
            start = idx + len(kw)
    return False


def special_group(*texts):
    """특수 대상 사업이면 그 이름을, 아니면 None 을 돌려준다.

    같은 키워드가 여러 번 나올 수 있어 첫 등장만 보지 않고 전부 훑되,
    제외 문구 바로 뒤에 나온 등장은 건너뛴다.
    """
    blob = " ".join(t for t in texts if t)
    if not blob:
        return None
    for name, kws in SPECIAL_GROUPS.items():
        for kw in kws:
            start = 0
            while True:
                idx = blob.find(kw, start)
                if idx == -1:
                    break
                if not _negated_near(blob, idx):
                    return name
                start = idx + len(kw)
    return None


# 사용자구분이 '개인' 이어도 실제로는 사업자만 받는 사업이 있다.
#   예) "수산물 수출 관련 개인 또는 단체" -> 수출업을 하는 사람
# 개인 자격으로 신청할 뿐, 그 업을 하지 않으면 해당되지 않는다.
_BUSINESS_ACTIVITY = (
    "수출", "수입", "무역", "가공생산", "제조", "판매", "유통", "도매",
    "출하", "양식", "조림", "벌목", "영림", "광업", "임업", "축산",
    "창업", "재창업", "소상공인", "소공인", "자영업",
)


def is_org_only(target: str, usr_type: str = "") -> bool:
    """개인이 아니라 기업·단체(또는 그 업 종사자)가 신청하는 사업인지.

    사용자구분 필드가 비어 있는 경우가 많아 지원대상 문구로도 판단한다.

    '제외' 문구 안에 든 말은 세지 않는다. 생계급여 지원대상에는
    "단, 아래는 제외 - 노숙인 자활시설 거주자"가 있는데, 여기 '시설'을
    근거로 삼으면 국민 누구나 받는 급여가 기업·단체 전용으로 찍혀
    조건 검색에서 통째로 사라진다.
    """
    head = (target or "")[:80]
    # 사업 활동을 전제로 한 표현이면 사용자구분과 무관하게 사업자용으로 본다
    if _has_real_match(head, _BUSINESS_ACTIVITY):
        return True
    if usr_type and "개인" in usr_type:
        return False
    t = target or ""
    if not t:
        return False
    if "개인" in t[:60]:
        return False
    return _has_real_match(t[:80], _ORG_ONLY_KW)

def blob_of(s):
    return " ".join(x for x in (s.get("name"), s.get("target"),
                               s.get("field"), s.get("content")) if x)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", help="이 태그만 본다")
    ap.add_argument("--show", type=int, default=6, help="태그당 보여줄 의심 항목 수")
    a = ap.parse_args()

    items = json.loads(DATA.read_text(encoding="utf-8"))["items"]

    order = [a.tag] if a.tag else list(CONFIRM)
    worst = []
    for tag in order:
        confirm = CONFIRM.get(tag)
        if not confirm:
            print(f"[{tag}] 확인 단어가 정의돼 있지 않습니다.")
            continue
        tagged = [s for s in items if tag in (s.get("tags") or [])]
        odd = [s for s in tagged if not any(k in blob_of(s) for k in confirm)]
        pct = len(odd) * 100 // max(len(tagged), 1)
        worst.append((pct, len(odd), len(tagged), tag))
        print(f"[{tag}] {len(tagged):,}건 중 의심 {len(odd):,}건 ({pct}%)")
        for s in odd[:a.show]:
            print(f"     · {(s.get('name') or '')[:56]}")
        print()

    if not a.tag:
        print("=== 의심 비율 높은 순 ===")
        for pct, n, tot, tag in sorted(worst, reverse=True):
            print(f"  {tag:10} {pct:3d}%  ({n:,}/{tot:,})")


if __name__ == "__main__":
    main()

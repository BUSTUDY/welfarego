        jc = f'<w:jc w:val="{align}"/>' if align != "left" else ""
        b_tag = "<w:b/><w:bCs/>" if bold else ""
        lines = str(text).split("\n")
        runs = []
        for idx, line in enumerate(lines):
            br = "<w:br/>" if idx > 0 else ""

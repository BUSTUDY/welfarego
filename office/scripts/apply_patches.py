#!/usr/bin/env python3
"""
Apply all Welfarego OFFICE source patches, custom branding graphics, Windows icons,
MSI wizard bitmaps, and autogen.input configuration to a LibreOffice core checkout.

Usage:
    python3 scripts/apply_patches.py --lo-dir /path/to/libreoffice-core [--check-only] [--external-tar /path/to/tar] [--spp-dir /path/to/spp]
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRAND_DIR = ROOT / "branding"
PATCHES_DIR = ROOT / "patches"
CONFIG_FILE = ROOT / "config" / "windows-x64.autogen.input"


def run_git(lo_dir: Path, args: list[str]) -> None:
    cmd = ["git", "-C", str(lo_dir), *args]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        sys.stderr.write(f"[ERROR] Command failed: {' '.join(cmd)}\n")
        if res.stdout:
            sys.stderr.write(res.stdout + "\n")
        if res.stderr:
            sys.stderr.write(res.stderr + "\n")
        sys.exit(res.returncode)


def apply_patches(lo_dir: Path, check_only: bool) -> list[Path]:
    patches = sorted(PATCHES_DIR.glob("*.patch"))
    if not patches:
        sys.exit(f"[ERROR] No patches found in {PATCHES_DIR}")

    for patch in patches:
        if check_only:
            print(f"[CHECK] {patch.name}")
            run_git(lo_dir, ["apply", "--check", str(patch)])
        else:
            print(f"[APPLY] {patch.name}")
            run_git(lo_dir, ["apply", "--check", str(patch)])
            run_git(lo_dir, ["apply", str(patch)])
    return patches


def copy_branding_assets(lo_dir: Path) -> None:
    # 1. Windows application & document ICO files -> sysui/desktop/icons/
    src_icons = BRAND_DIR / "icons"
    dst_icons = lo_dir / "sysui" / "desktop" / "icons"
    if dst_icons.is_dir():
        copied_icons = 0
        for ico in sorted(src_icons.glob("*.ico")):
            shutil.copy2(ico, dst_icons / ico.name)
            copied_icons += 1
        print(f"[BRAND] Replaced {copied_icons} Windows .ico files in {dst_icons}")
    else:
        print(f"[WARN] Skipped icon copy (directory not present in sparse checkout: {dst_icons})")

    # 2. MSI wizard bitmaps -> instsetoo_native/inc_common/windows/msi_templates/Binary/
    src_msi = BRAND_DIR / "msi"
    dst_msi = lo_dir / "instsetoo_native" / "inc_common" / "windows" / "msi_templates" / "Binary"
    if dst_msi.is_dir():
        for bmp in ("Banner.bmp", "Image.bmp", "Image_2.bmp"):
            shutil.copy2(src_msi / bmp, dst_msi / bmp)
        print(f"[BRAND] Replaced Windows MSI wizard bitmaps in {dst_msi}")
    else:
        print(f"[WARN] Skipped MSI bitmap copy (directory not present: {dst_msi})")

    # 3. Also overwrite colibre brand fallback assets so upstream LibreOffice graphics can never leak
    src_imgs = BRAND_DIR / "images"
    dst_colibre_brand = lo_dir / "icon-themes" / "colibre" / "brand"
    if dst_colibre_brand.is_dir():
        for png in ("intro.png", "intro-highres.png"):
            shutil.copy2(src_imgs / png, dst_colibre_brand / png)
        shell_dir = dst_colibre_brand / "shell"
        if shell_dir.is_dir():
            for svg in ("about.svg", "logo.svg", "logo_inverted.svg", "logo-sc.svg", "logo-sc_inverted.svg"):
                shutil.copy2(src_imgs / svg, shell_dir / svg)
        print(f"[BRAND] Updated colibre fallback brand artwork in {dst_colibre_brand}")

    # 4. Copy branding directory inside lo_dir/welfarego-branding for --with-branding
    dst_brand = lo_dir / "welfarego-branding"
    dst_brand.mkdir(parents=True, exist_ok=True)
    for fname in (
        "intro.png",
        "intro-highres.png",
        "about.svg",
        "logo.svg",
        "logo_inverted.svg",
        "logo-sc.svg",
        "logo-sc_inverted.svg",
    ):
        shutil.copy2(src_imgs / fname, dst_brand / fname)
    # progress.conf is sourced by Cygwin bash during configure.ac -> always enforce LF
    prog_text = (src_imgs / "progress.conf").read_text(encoding="utf-8").replace("\r\n", "\n")
    (dst_brand / "progress.conf").write_text(prog_text, encoding="utf-8", newline="\n")
    print(f"[BRAND] Prepared --with-branding directory at {dst_brand}")

    # 5. Copy Welfarego NOTICE / LICENSE / SOURCE-OFFER metadata into checkout
    dst_legal = lo_dir / "welfarego-legal"
    dst_legal.mkdir(parents=True, exist_ok=True)
    for doc in (ROOT / "LICENSE", ROOT / "NOTICE", ROOT / "legal" / "SOURCE-OFFER.md", ROOT / "legal" / "THIRD-PARTY-LICENSES.md"):
        shutil.copy2(doc, dst_legal / doc.name)


def write_autogen_input(
    lo_dir: Path,
    branding_path: str | None = None,
    external_tar: str | None = None,
    spp_dir: str | None = None,
    extra_buildid: str | None = None,
) -> None:
    lines = CONFIG_FILE.read_text(encoding="utf-8").splitlines()
    brand_arg = branding_path or (lo_dir / "welfarego-branding").as_posix()
    lines.append("")
    lines.append("# Generated by scripts/apply_patches.py")
    lines.append(f"--with-branding={brand_arg}")
    if external_tar:
        lines.append(f"--with-external-tar={external_tar}")
    if spp_dir:
        lines.append(f"--with-strawberry-perl-portable={spp_dir}")
    if extra_buildid:
        lines.append(f"--with-extra-buildid={extra_buildid}")

    target = lo_dir / "autogen.input"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"[CONFIG] Wrote {target}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Apply Welfarego OFFICE patches and branding to LibreOffice core.")
    parser.add_argument("--lo-dir", required=True, type=Path, help="Path to LibreOffice core checkout")
    parser.add_argument("--check-only", action="store_true", help="Only test patches without modifying files")
    parser.add_argument("--branding-arg", default=None, help="Explicit --with-branding path (e.g. Cygwin/WSL path)")
    parser.add_argument("--external-tar", default=None, help="Optional --with-external-tar path")
    parser.add_argument("--spp-dir", default=None, help="Optional --with-strawberry-perl-portable path")
    parser.add_argument("--extra-buildid", default="Welfarego OFFICE Modern Fluent Edition", help="Extra Build ID string")
    args = parser.parse_args()

    lo_dir = args.lo_dir.resolve()
    if not (lo_dir / "configure.ac").is_file():
        sys.exit(f"[ERROR] {lo_dir} does not look like a LibreOffice core repository (configure.ac missing).")

    brand = json.loads((BRAND_DIR / "brand.json").read_text(encoding="utf-8"))
    print(f"=== Preparing {brand['product_name']} {brand['package_version']} (base: {brand['upstream_tag']}) ===")

    if args.check_only:
        # Check patches sequentially inside a temporary check without keeping edits
        # Note: Patch 1 & 2 both touch Common.xcu cleanly sequentially; test via git apply --check on each
        apply_patches(lo_dir, check_only=True)
        print("[OK] All patches passed git apply --check.")
        return

    apply_patches(lo_dir, check_only=False)
    copy_branding_assets(lo_dir)
    write_autogen_input(
        lo_dir=lo_dir,
        branding_path=args.branding_arg,
        external_tar=args.external_tar,
        spp_dir=args.spp_dir,
        extra_buildid=args.extra_buildid,
    )
    print("[OK] Welfarego OFFICE source tree is ready to build.")


if __name__ == "__main__":
    main()
